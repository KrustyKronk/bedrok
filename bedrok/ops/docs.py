"""Generated pages: every wired source, the licence notices, the warnings, the
gaps and the chart house style.

  bedrok docs [--out DIR] [--check]

SOURCES and LICENSES are written from the source list (bedrok/seeds/sources.csv)
and the catalog (bedrok/seeds/macro_catalog.csv, plus the bulk families defined
in code); WARNINGS from bedrok/seeds/warnings.csv; GAPS from
bedrok/seeds/gaps.md and CHARTING from bedrok/seeds/charting.md, which ship in
the package so an install without the repo can serve them. None can drift from what Bedrok actually holds. A test fails when
the committed copies in docs/ differ from what this would write. The MCP server
serves the same texts as resources (bedrok://sources, bedrok://licenses,
bedrok://warnings, bedrok://gaps, bedrok://charting).

--check exits 1, writing nothing, when the files in --out are out of date.
"""
from __future__ import annotations

import argparse
import sys
from collections import Counter
from pathlib import Path

import pandas as pd

import importlib.resources

from bedrok.core import licensing, sources, warnings
from bedrok.core.aliases import ALIASES
from bedrok.ingest import derived, pipeline

HEADER = "<!-- Generated by `bedrok docs` from bedrok/seeds/. Do not edit by hand. -->\n\n"

_LICENSE_WORDS = {
    licensing.PUBLIC_DOMAIN: "public domain",
    licensing.ATTRIBUTION: "reuse with attribution",
    licensing.NONCOMMERCIAL: "non-commercial, with credit",
    licensing.FRED_CHANNEL: "FRED terms (never stored)",
    licensing.RESTRICTED: "personal use only",
}


def _catalog() -> pd.DataFrame:
    return pd.read_csv(pipeline.CATALOG_CSV, dtype=str).fillna("")


def _bulk_families() -> dict[str, list[str]]:
    """Series families registered by bulk stages rather than the seed, per source."""
    euro = [f"{s['label']} ({s['prefix']}*, {len(pipeline.family_geos(s))} "
            "geographies)" for s in pipeline.EUROSTAT_BULK_SETS]
    euro.insert(0, f"Broad-Europe HICP annual rates ({pipeline.HICP_PREFIX}*)")
    return {
        "eurostat": euro,
        "worldbank": ["Pink Sheet monthly commodity prices (wb_*)"],
        "cftc": ["Commitments of Traders net positioning (cot_*)"],
        "derived": [f"{d['series_id']} — {d['name']}" for d in derived.DERIVED],
    }


def sources_md() -> str:
    cat, rows, bulk = _catalog(), sources.load(), _bulk_families()
    counts = Counter(cat["source"])
    keyless = [s for s, r in rows.items() if r["key_required"] != "yes"]
    out = [HEADER, "# Sources\n\n",
           f"Bedrok is wired to {len(rows)} publishers. {len(keyless)} need no key at all; "
           "the others take a free key, entered in Bedrok's settings or its home folder's "
           "`.env` (see [INSTALL](INSTALL.md)). Every series is fetched from its publisher by "
           "your own copy of Bedrok; nothing is redistributed. Licence classes and what they "
           "ask of you are in [LICENSES](LICENSES.md).\n\n",
           "| Publisher | Series | Key | Licence | Stored | Terms |\n",
           "|---|---|---|---|---|---|\n"]
    for s, r in rows.items():
        n = counts.get(s, 0)
        series = f"{n} curated" if n else ""
        if s in bulk:
            fams = len(bulk[s])
            series = (series + " + " if series else "") + f"{fams} {'family' if fams == 1 else 'families'}"
        key = ("none" if not r["key_env"] else
               f"[`{r['key_env']}`]({r['key_url']})" + (" (optional)" if r["key_required"] == "optional" else ""))
        stored = "yes" if r["cache"] == licensing.STORE else "no — fetched live"
        terms = f"[terms]({r['terms_url']})" if r["terms_url"] else ""
        out.append(f"| **{r['name']}** (`{s}`) | {series} | {key} | "
                   f"{_LICENSE_WORDS.get(r['license'], r['license'])} | {stored} | {terms} |\n")
    out.append("\n## What each publisher covers\n")
    for s, r in rows.items():
        ids = cat.loc[cat["source"] == s, ["series_id", "name"]].values.tolist()
        if not ids and s not in bulk:
            continue
        out.append(f"\n### {r['name']}\n\n")
        for sid, name in ids:
            out.append(f"- `{sid}` — {name}\n")
        for fam in bulk.get(s, []):
            out.append(f"- {fam}\n")
    out.append(_aliases_md())
    return "".join(out)


def _aliases_md() -> str:
    out = ["\n## Ids that point elsewhere\n\n",
           "These ids still answer, with `alias_of` naming the one Bedrok keeps: the same "
           "number from the same dataset is held once.\n\n"]
    for alias, target in sorted(ALIASES.items()):
        out.append(f"- `{alias}` → `{target}`\n")
    return "".join(out)


def licenses_md() -> str:
    cat, rows = _catalog(), sources.load()
    out = [HEADER, "# Licence notices\n\n",
           "The Bedrok code is MIT. The data is not: every series keeps its publisher's "
           "terms. Your copy of Bedrok fetches each series from its publisher for your own "
           "use. When a number leaves your conversation — in a report, a chart, a post — "
           "carry the publisher's line below. The reasoning is in "
           "[LICENSING](LICENSING.md).\n\n",
           "## What the classes ask of you\n\n"]
    for cls, words in _LICENSE_WORDS.items():
        out.append(f"- **{words}** (`{cls}`)\n")
    out.append(
        "\nFRED's terms forbid storing its content, so every FRED series is fetched live "
        "and never written to the store. The IMF does not permit its content to be used "
        "to train large language models without permission; Bedrok stores and retrieves "
        "IMF numbers, it does not train on them, and the clause travels with every IMF "
        "series.\n\n")
    restricted = cat[cat["license"].isin([licensing.NONCOMMERCIAL, licensing.RESTRICTED])]
    if not restricted.empty:
        out.append("## Series with conditions beyond attribution\n\n")
        for _, r in restricted.sort_values(["license", "series_id"]).iterrows():
            out.append(f"- `{r['series_id']}` ({r['name']}) — "
                       f"{_LICENSE_WORDS[r['license']]}\n")
        out.append("\n")
    out.append("## Attribution, by publisher\n")
    for s, r in rows.items():
        out.append(f"\n### {r['name']}\n\n{r['attribution']}\n")
        if r["terms_url"]:
            out.append(f"\nTerms: <{r['terms_url']}>\n")
    out.append("\n### DG ECFIN (via Eurostat)\n\n" + licensing.ATTRIBUTIONS["dg_ecfin"] + "\n")
    out.append("\n## Additional notices for single series\n\n")
    for sid, text in licensing.SERIES_ATTRIBUTIONS.items():
        out.append(f"- `{sid}`: {text}\n")
    return "".join(out)


_SEVERITY_WORDS = {
    "disqualifying": "Disqualifying — do not use the official number for this period",
    "material": "Material — use only with the cross-check",
    "caveat": "Caveat — read before relying on it",
}


def warnings_md() -> str:
    rows = warnings.load()
    out = [HEADER, "# When the official number is in doubt\n\n",
           f"{len(rows)} documented cases where an official statistic should not be taken "
           "at face value: a release suspended or withheld, a month never collected, a "
           "rebase that broke a series, a figure later restated. Each says what happened, "
           "what it did to the numbers, what to compare against, and where it is "
           "documented. Bedrok attaches a case to the series it touches; most concern "
           "countries Bedrok does not carry, and are here so an assistant can say so.\n\n"
           "Disqualifying and material cases ride on every answer that quotes numbers "
           "from their period. Caveats appear when a series is described or searched for.\n"]
    for sev in warnings.SEVERITIES:
        group = sorted((r for r in rows if r["severity"] == sev),
                       key=lambda r: (r["country"], r["period_start"]))
        if not group:
            continue
        out.append(f"\n## {_SEVERITY_WORDS[sev]}\n")
        for r in group:
            period = r["period_start"] + ("–" + r["period_end"] if r["period_end"] else " onward")
            out.append(f"\n### {r['country']}: {r['official_series']} ({period})\n\n"
                       f"{r['what_happened']} {r['effect_on_data']}\n\n"
                       f"- Cross-check: {r['cross_check']}\n")
            if r["source_url"]:
                out.append(f"- Source: [{r['source_name']}]({r['source_url']})\n")
            if r["series"]:
                out.append("- Bedrok series: " + ", ".join(f"`{i}`" for i in r["series"].split()) + "\n")
    return "".join(out)


def _seed_page(name: str) -> str:
    return HEADER + (importlib.resources.files("bedrok") / "seeds" / name).read_text(encoding="utf-8")


def gaps_md() -> str:
    return _seed_page("gaps.md")


def charting_md() -> str:
    return _seed_page("charting.md")


PAGES = {"SOURCES.md": sources_md, "LICENSES.md": licenses_md,
         "WARNINGS.md": warnings_md, "GAPS.md": gaps_md, "CHARTING.md": charting_md}


def main() -> int:
    ap = argparse.ArgumentParser(prog="bedrok docs")
    ap.add_argument("--out", default="docs", help="directory to write into (default: ./docs)")
    ap.add_argument("--check", action="store_true",
                    help="exit 1 if the files in --out are out of date; write nothing")
    args = ap.parse_args()
    out = Path(args.out)
    stale = []
    for name, render in PAGES.items():
        text, path = render(), out / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                stale.append(name)
        else:
            out.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
            print(f"wrote {path}")
    if stale:
        print(f"out of date: {', '.join(stale)} — run `bedrok docs`")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
